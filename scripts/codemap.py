"""Write (or check) the per-file code map: one line per source file, "path - what it does [uses ...]".

Agents read the map instead of opening files: the summary is the module docstring (Python) or the
first comment (TypeScript, JavaScript, shell); a file with none is flagged "(no docstring)". Run
`python scripts/codemap.py` to rewrite docs/reference/codemap.md, `--check` to fail when it is stale
(CI and the pre-push check do this). Other repositories: `--root PATH --all --out FILE`.
Dashboard source is listed one line per folder (563 files would bury the rest).
"""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = "docs/reference/codemap.md"
PER_FILE = ("scripts/", "services/")
PER_FOLDER = ("dashboard/src", "dashboard/e2e", "dashboard/scripts")
CODE = {".py", ".ts", ".tsx", ".js", ".mjs", ".cjs", ".sh"}
LIMIT = 120
MISSING = "(no docstring)"
HEADER = """# Code map

Generated by `python scripts/codemap.py` (CI fails when it is stale). One line per file:
`path - what it does [uses: local modules]`. Read this first; open a file only when the map points to it.
"""


def tracked(root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True)
    return sorted(line for line in out.stdout.splitlines() if Path(line).suffix in CODE)


def squash(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def python_summary(path: Path, local: set[str]) -> tuple[str, list[str]]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return MISSING, []
    doc = ast.get_docstring(tree)
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".")[-1] for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.module:
                names.add(node.module.split(".")[-1])
            names.update(alias.name for alias in node.names)
    uses = sorted(name for name in names & local if name != path.stem)
    return (squash(doc.split("\n\n")[0]) if doc else MISSING), uses


def comment_summary(path: Path) -> str:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()[:25]
    except UnicodeDecodeError:
        return MISSING
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith(("#!", "'use strict'", '"use strict"')):
            continue
        if line.startswith(("//", "#")):
            return squash(line.lstrip("/# "))
        if line.startswith(("/*", "*")):
            return squash(line.strip("/* "))
        break
    return MISSING


def clip(line: str) -> str:
    return line if len(line) <= LIMIT else line[: LIMIT - 3].rstrip() + "..."


def file_line(root: Path, rel: str, local: set[str]) -> str:
    path = root / rel
    if path.suffix != ".py":
        return clip(f"{rel} - {comment_summary(path)}")
    summary, uses = python_summary(path, local)
    summary_room = LIMIT - len(f"{rel} - ")
    tail = ""
    for count in (4, 3, 2, 1):
        candidate = f" [uses: {', '.join(uses[:count])}]" if uses else ""
        if summary_room - len(candidate) >= min(len(summary), 70):
            tail = candidate
            break
    room = summary_room - len(tail)
    if len(summary) > room:
        summary = summary[: max(room - 3, 10)].rstrip() + "..."
    return f"{rel} - {summary}{tail}"


def folder_lines(files: list[str], folder: str) -> list[str]:
    by_dir: dict[str, list[str]] = {}
    for rel in files:
        if rel.startswith(folder + "/"):
            by_dir.setdefault(Path(rel).parent.as_posix(), []).append(Path(rel).stem)
    return [clip(f"{d}/ - {len(s)} files: {', '.join(sorted(s))}") for d, s in sorted(by_dir.items())]


def render(root: Path, everything: bool) -> str:
    files = tracked(root)
    local = {Path(rel).stem for rel in files if rel.endswith(".py")}
    if everything:
        listed = [rel for rel in files if not rel.startswith(("tests/", "test/"))]
    else:
        listed = [rel for rel in files if rel.startswith(PER_FILE)]
    body = [file_line(root, rel, local) for rel in listed]
    missing = sum(MISSING in line for line in body)
    if not everything:
        for folder in PER_FOLDER:
            body += folder_lines(files, folder)
    return HEADER + f"\n{len(body)} entries; {missing} files without a docstring.\n\n" + "\n".join(body) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the map is out of date")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--all", action="store_true", help="every source file outside tests/ (gate repos)")
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    text = render(root, args.all)
    out = Path(args.out) if Path(args.out).is_absolute() else root / args.out
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{args.out} is out of date; run python scripts/codemap.py", file=sys.stderr)
            return 1
        print("code map is up to date.")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {out} ({text.count(chr(10))} lines).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
