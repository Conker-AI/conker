// Vendor the brand logos the dashboard shows into src/components/brand/brand-icons.ts.
//
//   node scripts/brand-icons.mjs
//
// AI companies come from @lobehub/icons-static-svg (MIT), services from simple-icons (CC0-1.0), both
// at pinned versions from unpkg. Only one path per logo is kept and drawn in currentColor, so every
// logo takes the theme's text color (no brand colors in the shell). To add one: put it in a list
// below, run this, commit the result.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const lobe = { version: "1.101.0", url: (name) => `https://unpkg.com/@lobehub/icons-static-svg@1.101.0/icons/${name}.svg` }
const simple = { version: "16.36.0", url: (name) => `https://unpkg.com/simple-icons@16.36.0/icons/${name}.svg` }
// id in Conker -> [source, file name]
const icons = {
  openai: [lobe, "openai"], claude: [lobe, "claude"], anthropic: [lobe, "anthropic"], gemini: [lobe, "gemini"],
  xai: [lobe, "grok"], mistral: [lobe, "mistral"], deepseek: [lobe, "deepseek"], openrouter: [lobe, "openrouter"],
  ollama: [lobe, "ollama"],
  tiktok: [simple, "tiktok"], github: [simple, "github"], gmail: [simple, "gmail"], telegram: [simple, "telegram"],
  youtube: [simple, "youtube"], google: [simple, "google"], googlecalendar: [simple, "googlecalendar"],
  googledrive: [simple, "googledrive"], discord: [simple, "discord"], notion: [simple, "notion"], x: [simple, "x"],
  whatsapp: [simple, "whatsapp"], spotify: [simple, "spotify"], reddit: [simple, "reddit"],
  instagram: [simple, "instagram"], dropbox: [simple, "dropbox"],
}

const here = path.dirname(fileURLToPath(import.meta.url))
const target = path.resolve(here, "../src/components/brand/brand-icons.ts")
const lines = []
for (const [id, [source, name]] of Object.entries(icons)) {
  const response = await fetch(source.url(name))
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`)
  const svg = await response.text()
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1])
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1]
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  if (paths.length !== 1 || !title || viewBox !== "0 0 24 24") throw new Error(`${name}: expected one path, a title and a 24px view box`)
  lines.push(`  ${id}: { title: ${JSON.stringify(title)}, path: ${JSON.stringify(paths[0])}, evenOdd: ${/fill-rule="evenodd"/.test(svg)} },`)
}
const text = `// Generated by scripts/brand-icons.mjs; do not edit by hand.
// AI company logos: @lobehub/icons-static-svg ${lobe.version}, MIT License, Copyright (c) 2023 LobeHub.
// Service logos: simple-icons ${simple.version}, CC0-1.0. Logos are trademarks of their owners and
// only name the service a thing connects to.

export type BrandIcon = { title: string; path: string; evenOdd: boolean }

export const brandIcons = {
${lines.join("\n")}
} satisfies Record<string, BrandIcon>

export type BrandId = keyof typeof brandIcons
`
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, text)
console.log(`${Object.keys(icons).length} logos -> ${path.relative(process.cwd(), target)}`)
