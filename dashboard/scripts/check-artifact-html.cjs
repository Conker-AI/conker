const assert = require('node:assert/strict')
const path = require('node:path')
const { createRequire } = require('node:module')
const root = path.resolve(__dirname, '..')
const fromRoot = createRequire(path.join(root, 'package.json'))
const { buildSync } = createRequire(fromRoot.resolve('vite'))('esbuild')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const result = buildSync({ stdin: { contents: 'export * from "./src/lib/artifact-html"; export {ArtifactHtmlPreview} from "./src/components/artifacts/html-preview";', resolveDir: root }, write: false, bundle: true, platform: 'node', format: 'cjs', external: ['react', 'react/*'], tsconfig: path.join(root, 'tsconfig.app.json'), logLevel: 'silent' })
const compiled = { exports: {} }
new Function('require', 'module', 'exports', result.outputFiles[0].text)(fromRoot, compiled, compiled.exports)
const { artifactHtmlDocument, ARTIFACT_HTML_CSP, ARTIFACT_HTML_SANDBOX, ArtifactHtmlPreview } = compiled.exports
const hostile = '"></iframe><script>parent.document.body.textContent="escape"</script><meta http-equiv="refresh" content="0;url=https://example.com"><p>&quot; data</p>'
const initial = renderToStaticMarkup(React.createElement(ArtifactHtmlPreview, { content: { text: hostile } }))
assert.ok(initial.includes('Run preview'))
assert.ok(!/<(?:iframe|script|meta)\b/.test(initial), 'Initial rendering must expose no executable document or frame')
assert.ok(!initial.includes('parent.document'), 'Source must not be inserted into the host document')
const empty = renderToStaticMarkup(React.createElement(ArtifactHtmlPreview, { content: { text: '' } }))
assert.ok(empty.includes('This HTML artifact is empty'))
assert.ok(!empty.includes('<iframe'))
assert.equal(ARTIFACT_HTML_SANDBOX, 'allow-scripts', 'No same-origin, popup, download, form or navigation permissions')
for (const directive of ["default-src 'none'", "connect-src 'none'", "frame-src 'none'", "worker-src 'none'", "object-src 'none'", "form-action 'none'", "base-uri 'none'", "script-src 'unsafe-inline'", "style-src 'unsafe-inline'", 'img-src data:']) assert.ok(ARTIFACT_HTML_CSP.includes(directive))
assert.ok(!ARTIFACT_HTML_CSP.includes('unsafe-eval'))
const document = artifactHtmlDocument(hostile)
assert.equal((document.match(/<iframe\b/g) || []).length, 1, 'Hostile source cannot create a sibling in the trusted wrapper')
assert.ok(document.includes('sandbox="allow-scripts"'))
assert.ok(document.includes('referrerpolicy="no-referrer"'))
assert.ok(!document.includes('<script>parent.document'))
const encoded = document.match(/srcdoc="([^"]*)"/)[1]
const inner = encoded.replaceAll('&quot;', '"').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&')
assert.ok(inner.includes(hostile), 'The exact owner source survives attribute escaping')
assert.ok(inner.indexOf('Content-Security-Policy') < inner.indexOf(hostile), 'CSP is installed before owner content')
assert.ok(document.indexOf('Content-Security-Policy') < document.indexOf('<iframe'))
assert.throws(() => artifactHtmlDocument('x'.repeat(200001)), /200,000/)
console.log('HTML preview checks passed: explicit-run inert render, strict sandbox permissions, trusted wrapper CSP, source escaping and size bounds. Browser enforcement requires separate adversarial verification.')
