// Generate TypeScript types for Pi's and the gateway's HTTP APIs from their OpenAPI documents.
//
//   node scripts/api-types.mjs [--check]
//
// The documents are Pi's at the commit ../scripts/workspace-sources.json pins, so the UI (and its
// typed client, src/lib/gateway/pi-client.ts) is typed against the API it runs with. CI checks out
// that commit and passes PI_DOCS; without it, they are read with `git show` from the local Pi
// repository (PI_REPO, or gates/pi next to this checkout or its worktree folder), so a local run
// never compares against a Pi that has moved on. --check fails when the committed files differ.
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, "../..")
const output = path.resolve(here, "../src/lib/api/generated")
const pin = JSON.parse(fs.readFileSync(path.join(repo, "scripts/workspace-sources.json"), "utf8")).pi
const piRepo = process.env.PI_REPO ?? [path.resolve(repo, "../gates/pi"), path.resolve(repo, "../../gates/pi")].find(dir => fs.existsSync(path.join(dir, ".git")))
function read(source) {
  if (process.env.PI_DOCS) return fs.readFileSync(path.join(path.resolve(here, "..", process.env.PI_DOCS), source), "utf8")
  if (!piRepo) throw new Error("No Pi repository found: set PI_DOCS (a docs folder) or PI_REPO (a Pi checkout).")
  try {
    return execFileSync("git", ["-C", piRepo, "show", `${pin}:docs/${source}`], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  } catch {
    throw new Error(`Pi commit ${pin} is not in ${piRepo}; run git -C ${piRepo} fetch, or set PI_DOCS.`)
  }
}
const targets = { "pi.d.ts": "pi-openapi.json", "gateway.d.ts": "gateway-openapi.json" }
const header = (source) =>
  `// Generated by scripts/api-types.mjs from Pi's docs/${source}; do not edit by hand.\n` +
  "// Regenerate with: npm run api:types\n\n"

const stale = []
for (const [file, source] of Object.entries(targets)) {
  const document = JSON.parse(read(source))
  const text = header(source) + astToString(await openapiTS(document))
  const target = path.join(output, file)
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) stale.push(file)
  } else {
    fs.mkdirSync(output, { recursive: true })
    fs.writeFileSync(target, text)
    console.log(`wrote src/lib/api/generated/${file}`)
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(", ")}. Run npm run api:types against the pinned Pi docs.`)
  process.exit(1)
}
