// Generate TypeScript types for Pi's and the gateway's HTTP APIs from their OpenAPI documents.
//
//   node scripts/api-types.mjs [--check]
//
// The documents come from the Pi checkout (PI_DOCS, default ../../gates/pi/docs), which CI pins to
// the commit in ../scripts/workspace-sources.json, so the UI is typed against the API it runs with.
// --check fails when the committed files differ from what the documents generate.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = path.dirname(fileURLToPath(import.meta.url))
const docs = path.resolve(here, "..", process.env.PI_DOCS ?? "../../gates/pi/docs")
const output = path.resolve(here, "../src/lib/api/generated")
const targets = { "pi.d.ts": "pi-openapi.json", "gateway.d.ts": "gateway-openapi.json" }
const header = (source) =>
  `// Generated by scripts/api-types.mjs from Pi's docs/${source}; do not edit by hand.\n` +
  "// Regenerate with: npm run api:types\n\n"

const stale = []
for (const [file, source] of Object.entries(targets)) {
  const document = JSON.parse(fs.readFileSync(path.join(docs, source), "utf8"))
  const text = header(source) + astToString(await openapiTS(document))
  const target = path.join(output, file)
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) stale.push(file)
  } else {
    fs.mkdirSync(output, { recursive: true })
    fs.writeFileSync(target, text)
    console.log(`wrote src/lib/api/generated/${file}`)
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(", ")}. Run npm run api:types against the pinned Pi docs.`)
  process.exit(1)
}
