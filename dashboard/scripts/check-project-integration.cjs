const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const cache = new Map()
globalThis.crypto ??= require('node:crypto').webcrypto
function load(relative) {
  if (cache.has(relative)) return cache.get(relative).exports
  const module = { exports: {} }
  cache.set(relative, module)
  const source = fs.readFileSync(path.join(root, relative), 'utf8').replaceAll('import.meta.env', '({})')
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText
  new Function('require', 'module', 'exports', code)(request => {
    if (request === 'zod') return require('zod')
    assert.ok(request.startsWith('.'), `Unexpected dependency: ${request}`)
    return load(`${path.posix.normalize(path.posix.join(path.posix.dirname(relative), request))}.ts`)
  }, module, module.exports)
  return module.exports
}
async function main() {
  const { createFixtureClient } = load('src/lib/api/fixture-adapter.ts')
  const { projectPreviewState } = load('src/lib/api/project-snapshot.ts')
  const { createProjectPreviewClient } = load('src/lib/api/project-preview.ts')
  const client = createFixtureClient(), initial = await client.load()
  assert.deepEqual(initial.projects, [])
  const agent = initial.agents.find(item => item.kind === 'agent' && !item.archivedAt)
  const origin = await client.createConversation(agent.id)
  await client.sendMessage(origin.id, 'Research the linked evidence.')
  const destination = await client.createConversation(agent.id)
  assert.notEqual(origin.id, destination.id)
  await client.updateConversation(origin.id, { title: 'Private project research' })
  const taskInput = { outcome: 'Review project evidence', criteria: ['Owner reviewed citations'], agentId: agent.id, sessionId: origin.id }
  let task = await client.tasks.create(taskInput)
  const reading = initial.sessions.find(session => initial.conversations[session.id]?.files.length)
  assert.ok(reading, 'A fixture conversation provides existing file references')
  const file = initial.conversations[reading.id].files[0]
  const fileRef = { kind: 'file', sessionId: reading.id, fileId: file.id }
  let project = await client.projects.create({ name: 'Evidence review', description: 'References only', instructions: 'Cite original evidence.' })
  const chatRef = { kind: 'conversation', sessionId: origin.id }
  const taskRef = { kind: 'task', taskId: task.id }
  for (const reference of [chatRef, taskRef, fileRef]) project = await client.projects.link(project.id, reference, project.revision)
  const before = await client.load()
  assert.equal(before.projects[0].links.length, 3)
  assert.ok(before.projects[0].links.every(link => !('label' in link) && !('content' in link)))
  const publicTarget = { memoryDisabled: false, harnessDisabled: false }
  let preview = await client.projects.previewContext(project.id, publicTarget)
  assert.equal(preview.references.length, 3)
  assert.equal(preview.contentIncluded, false)
  assert.equal(preview.memoryWritesAllowed, false)
  assert.equal(preview.grantsInherited, false)
  assert.deepEqual((await client.load()).conversations, before.conversations, 'Project preview never changes canonical conversations')
  await client.updateConversation(origin.id, { privacy: { memoryDisabled: true } })
  const privateView = await client.projects.get(project.id)
  assert.ok(privateView.links.filter(link => link.reference.kind !== 'file').every(link => link.privacy.memoryDisabled && link.incognito))
  preview = await client.projects.previewContext(project.id, publicTarget)
  assert.equal(preview.references.length, 1)
  assert.equal(preview.excluded.filter(item => item.reason === 'origin-private').length, 2)
  assert.equal((await client.projects.search(project.id, 'project')).links.length, 2, 'Owner metadata search remains available without helper retrieval')
  await client.updateConversation(origin.id, { privacy: { memoryDisabled: false, harnessDisabled: true } })
  assert.equal((await client.projects.previewContext(project.id, publicTarget)).references.length, 1)
  await client.updateConversation(origin.id, { incognito: false })
  assert.equal((await client.projects.previewContext(project.id, { ...publicTarget, incognito: true })).references.length, 0)
  await client.updateConversation(origin.id, { title: 'Revised origin', archived: true })
  assert.ok((await client.projects.get(project.id)).links.filter(link => link.reference.kind !== 'file').every(link => link.availability === 'archived'))
  assert.equal((await client.projects.previewContext(project.id, publicTarget)).references.length, 1)
  await client.updateConversation(origin.id, { archived: false })
  assert.equal((await client.projects.get(project.id)).links[0].label, 'Revised origin')
  task = await client.tasks.update(task.id, { ...taskInput, sessionId: destination.id }, task.revision)
  assert.equal((await client.projects.get(project.id)).links[1].availability, 'origin-changed')
  assert.equal((await client.projects.get(project.id)).links[1].label, 'Unavailable reference')
  await assert.rejects(client.projects.link(project.id, taskRef, project.revision), /origin changed/)
  project = await client.projects.unlink(project.id, taskRef, project.revision)
  project = await client.projects.link(project.id, taskRef, project.revision)
  assert.equal(project.links.at(-1).snapshot.originSessionId, destination.id)
  task = await client.tasks.cancel(task.id, 'Owner cancelled after review.', task.revision)
  await client.tasks.archive(task.id, true, task.revision)
  assert.equal((await client.projects.get(project.id)).links.at(-1).availability, 'archived')
  const fork = await client.forkConversation(reading.id, initial.conversations[reading.id].messages[0].id)
  assert.ok((await client.load()).conversations[fork.id].files.some(item => item.id === file.id))
  await client.deleteConversation(reading.id)
  assert.equal((await client.projects.get(project.id)).links.find(link => link.reference.kind === 'file').availability, 'unavailable', 'Duplicate file ID in fork cannot replace a deleted origin')
  await client.deleteConversation(origin.id)
  assert.equal((await client.projects.get(project.id)).links[0].availability, 'unavailable', 'Project references do not block source deletion')
  assert.equal((await client.projects.search(project.id, file.name)).links.length, 0)
  const snapshot = await client.load()
  const mapped = projectPreviewState(snapshot)
  assert.ok(mapped.files.every(item => Object.keys(item).sort().join(',') === 'id,name,sessionId'))
  assert.ok(mapped.sessions.every(item => !('messages' in item)), 'Project projection contains no transcript or grant data')
  delete snapshot.conversations[destination.id].privacy
  const unknownPrivacy = createProjectPreviewClient({ getSnapshot: () => projectPreviewState(snapshot), setProjects: () => assert.fail('Read operation cannot commit') })
  assert.equal((await unknownPrivacy.get(project.id)).links.at(-1).availability, 'unavailable', 'Missing canonical privacy fails closed through adapter mapping')
  project = await client.projects.get(project.id)
  project = await client.projects.archive(project.id, true, project.revision)
  assert.equal((await client.projects.previewContext(project.id, publicTarget)).instruction, null)
  await assert.rejects(client.projects.remove(project.id, project.revision), /empty archived/)
  project = await client.projects.archive(project.id, false, project.revision)
  for (const reference of [chatRef, taskRef, fileRef]) project = await client.projects.unlink(project.id, reference, project.revision)
  project = await client.projects.archive(project.id, true, project.revision)
  const sourcesBeforeRemoval = await client.load()
  await client.projects.remove(project.id, project.revision)
  const after = await client.load()
  assert.deepEqual(after.tasks, sourcesBeforeRemoval.tasks)
  assert.deepEqual(after.sessions, sourcesBeforeRemoval.sessions)
  assert.deepEqual(after.conversations, sourcesBeforeRemoval.conversations)
  assert.deepEqual((await createFixtureClient().load()).projects, [])
  console.log('Project adapter privacy, source identity, task movement/archive, deleted files/conversations, reference-only projection and isolation checks passed.')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
