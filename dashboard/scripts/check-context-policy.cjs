const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const source = fs.readFileSync(path.resolve(__dirname, '../src/lib/api/context-policy.ts'), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } })
const loaded = { exports: {} }
new Function('require', 'module', 'exports', compiled.outputText)(() => { throw new Error('Context policy must have no runtime dependencies') }, loaded, loaded.exports)
const { createContextPolicy, normalizeContextPolicy, estimateContextTokens, planContext } = loaded.exports
const privacy = { memoryDisabled: false, harnessDisabled: false }
const message = (id, text, extra = {}) => ({ id, text, role: 'user', createdAt: '2026-09-20T00:00:00Z', ...extra })
const base = createContextPolicy(1000, 100)
for (const budget of [{ contextWindowTokens: 0 }, { outputReserveTokens: 0 }, { outputReserveTokens: 1000 }, { otherInputTokens: -1 }, { outputReserveTokens: 1.5 }, { contextWindowTokens: Infinity }]) assert.throws(() => normalizeContextPolicy({ ...base, budget: { ...base.budget, ...budget } }), /reserve/)
assert.throws(() => normalizeContextPolicy({ ...base, sessionInstructions: 'x'.repeat(16001) }), /instructions/)
assert.throws(() => normalizeContextPolicy({ ...base, messagePolicies: { a: 'truncate' } }), /supported/)
assert.throws(() => normalizeContextPolicy({ ...base, messagePolicies: JSON.parse('{"__proto__":"exclude"}') }), /supported/)
const messages = [message('pin', 'Keep every word.', { pinned: true }), message('ordinary', 'No fake summary.', { role: 'assistant', activity: { secretReasoning: 'NEVER COPY THIS' } }), message('omit', 'EXCLUDED CONTENT'), message('redacted', 'REDACTED CONTENT', { redacted: true })]
const policy = { ...base, sessionInstructions: '  Keep my instructions exact.\n', messagePolicies: { omit: 'exclude' }, budget: { ...base.budget, otherInputTokens: 25 } }
const plan = planContext({ policy, messages, privacy, inheritedInstructions: [{ scope: 'project', text: 'Project instruction' }, { scope: 'global', text: 'Global instruction' }, { scope: 'agent', text: 'Agent instruction' }] })
assert.deepEqual(plan.instructions.map(layer => layer.scope), ['global', 'agent', 'project', 'session'])
assert.equal(plan.instructions[3].text, policy.sessionInstructions, 'Instructions are outside history and retain exact whitespace')
assert.equal(plan.messages[0].effectivePolicy, 'keep-exact')
assert.equal(plan.messages[1].text, 'No fake summary.')
assert.deepEqual(plan.summaryEligibleMessageIds, ['ordinary'])
assert.equal(plan.messages[2].text, undefined)
assert.equal(plan.messages[3].text, undefined)
assert.ok(!JSON.stringify(plan).includes('NEVER COPY THIS'))
assert.ok(!JSON.stringify(plan).includes('REDACTED CONTENT'))
assert.ok(!JSON.stringify(plan).includes('EXCLUDED CONTENT'))
assert.equal(plan.budget.estimatedTotalTokens, plan.budget.instructionTokens + plan.budget.historyTokens + 25 + 100)
assert.equal(plan.nextAction, 'within-estimated-budget')
assert.match(plan.estimateLabel, /not provider-tokenized/)
assert.equal(plan.helpers.providerAuthorization, 'not-evaluated')
const conflict = planContext({ policy: { ...base, messagePolicies: { pin: 'exclude' } }, messages, privacy })
assert.ok(conflict.conflicts.some(item => item.code === 'pinned-policy'))
assert.equal(conflict.messages[0].text, messages[0].text, 'A conflicting policy never silently drops a pin')
assert.equal(conflict.nextAction, 'review-conflicts')
const over = planContext({ policy: { ...createContextPolicy(30, 10), sessionInstructions: 'Instructions remain '.repeat(10) }, messages: [message('large', 'Pinned text '.repeat(30), { pinned: true })], privacy })
assert.ok(over.budget.overflowTokens > 0)
assert.equal(over.budget.remainingInputTokens, 0)
assert.equal(over.nextAction, 'fork-required')
assert.equal(over.messages[0].text, 'Pinned text '.repeat(30))
assert.equal(over.instructions[0].text, 'Instructions remain '.repeat(10))
const retrievePolicy = { ...base, messagePolicies: { a: 'retrieve', b: 'allow-summary' } }
const candidates = [message('a', 'Original session evidence'), message('b', 'Exact until a reviewed summary exists')]
for (const memoryDisabled of [false, true]) for (const harnessDisabled of [false, true]) {
  const result = planContext({ policy: retrievePolicy, messages: candidates, privacy: { memoryDisabled, harnessDisabled } })
  assert.equal(result.helpers.memoryReadsAllowed, !memoryDisabled)
  assert.equal(result.helpers.memoryWritesAllowed, !memoryDisabled)
  assert.equal(result.helpers.sessionRetrievalEligible, !harnessDisabled, 'No memory and no harness are distinct')
  assert.equal(result.helpers.summaryEligible, !harnessDisabled)
  assert.equal(result.messages[0].text, undefined)
  assert.equal(result.messages[0].estimatedTokens, 0)
  assert.equal(result.messages[0].disposition, harnessDisabled ? 'retrieval-disabled' : 'retrieval-pending')
  assert.equal(result.messages[1].text, candidates[1].text, 'No harness never drops ordinary history')
  assert.deepEqual(result.summaryEligibleMessageIds, harnessDisabled ? [] : ['b'])
  assert.equal(result.nextAction, harnessDisabled ? 'review-conflicts' : 'resolve-retrieval')
}
const missing = planContext({ policy: { ...base, messagePolicies: { later: 'keep-exact' } }, messages: candidates, privacy })
assert.ok(missing.conflicts.some(item => item.code === 'missing-message'))
assert.ok(!missing.messages.some(row => row.messageId === 'later'), 'Never fetches another branch or future turn')
const redactedPin = planContext({ policy: base, messages: [message('gone', 'DO NOT RESTORE', { pinned: true, redacted: true })], privacy })
assert.equal(redactedPin.conflicts[0].code, 'unavailable-pin')
assert.ok(!JSON.stringify(redactedPin).includes('DO NOT RESTORE'))
assert.throws(() => planContext({ policy: base, messages: [message('same', 'one'), message('same', 'two')], privacy }), /unique/)
assert.throws(() => planContext({ policy: base, messages: [], privacy: { memoryDisabled: true } }), /independent/)
assert.throws(() => planContext({ policy: base, messages: [], privacy, inheritedInstructions: [{ scope: 'agent', text: 'One' }, { scope: 'agent', text: 'Two' }] }), /at most one/)
const before = JSON.stringify({ policy, messages, privacy })
plan.messages[0].text = 'Edited inspector copy'
plan.instructions[0].text = 'Edited layer'
assert.equal(JSON.stringify({ policy, messages, privacy }), before, 'No source mutation or history rewriting')
const cloned = normalizeContextPolicy(policy)
cloned.messagePolicies.omit = 'keep-exact'
assert.equal(policy.messagePolicies.omit, 'exclude')
assert.equal(estimateContextTokens(''), 0)
assert.ok(estimateContextTokens('Привет עולם') > 0)
assert.deepEqual(planContext({ policy, messages, privacy }), planContext({ policy, messages, privacy }), 'Planning is deterministic')
console.log('Context policy checks passed: budgets/reserves, exact pins/instructions, overflow/fork, privacy separation, branch boundaries, no fabricated summary, no redacted/activity leakage, isolation and deterministic estimates.')
