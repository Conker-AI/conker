const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const root = path.resolve(__dirname, '..')
const cache = new Map()
globalThis.crypto ??= require('node:crypto').webcrypto
function load(relative) {
  if (cache.has(relative)) return cache.get(relative).exports
  const module = { exports: {} }
  cache.set(relative, module)
  const source = fs.readFileSync(path.join(root, relative), 'utf8').replaceAll('import.meta.env', '({})')
  const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText
  new Function('require', 'module', 'exports', code)(request => {
    if (request === 'zod') return require('zod')
    assert.ok(request.startsWith('.'), `Unexpected dependency: ${request}`)
    return load(`${path.posix.normalize(path.posix.join(path.posix.dirname(relative), request))}.ts`)
  }, module, module.exports)
  return module.exports
}
async function main() {
  const { createFixtureClient } = load('src/lib/api/fixture-adapter.ts')
  for (const change of ['redact', 'delete', 'edit']) {
    const client = createFixtureClient(), initial = await client.load()
    const session = initial.sessions.find(item => item.id !== initial.companionSessionId && initial.conversations[item.id]?.messages.at(-1)?.role === 'assistant')
    const message = initial.conversations[session.id].messages.at(-1)
    const secret = `PRIVATE_SOURCE_BODY_${change}`
    await client.updateMessage(session.id, message.id, { text: secret })
    const artifact = await client.artifacts.createFromMessage({ sessionId: session.id, messageId: message.id, title: 'Explicit source copy' })
    const edited = await client.artifacts.appendVersion(artifact.id, { content: { kind: 'markdown', text: `OWNER_EDIT_OF_${secret}` } }, artifact.revision)
    const before = await client.load()
    assert.equal(before.artifacts[0].versions.length, 2)
    assert.ok(!JSON.stringify(before.artifacts).includes('sourceTextAtCreation'), 'Comparison source text is internal only')
    before.artifacts[0].versions[0].content.text = 'Caller mutation'
    assert.equal((await client.artifacts.get(artifact.id)).versions[0].content.text, secret)
    const overlappingLoad = client.load()
    if (change === 'redact') await client.updateMessage(session.id, message.id, { redacted: true })
    else if (change === 'delete') await client.deleteConversation(session.id)
    else await client.updateMessage(session.id, message.id, { text: 'Revised source response' })
    for (const view of [(await overlappingLoad).artifacts[0], (await client.load()).artifacts[0], await client.artifacts.get(artifact.id), (await client.artifacts.list())[0]]) {
      assert.equal(view.availability, change === 'redact' ? 'source-redacted' : change === 'delete' ? 'source-unavailable' : 'source-changed')
      assert.deepEqual(view.versions, [])
      assert.equal(view.versionCount, 2)
      assert.ok(!JSON.stringify(view).includes(secret), 'No source-derived or subsequently edited body survives in safe views')
      assert.ok(!('sourceTextAtCreation' in view))
    }
    await assert.rejects(client.artifacts.export(artifact.id), /blocked/)
    await assert.rejects(client.artifacts.export(artifact.id, 1), /blocked/)
    await assert.rejects(client.artifacts.appendVersion(artifact.id, { content: { kind: 'markdown', text: 'New' } }, edited.revision), /available/)
    await assert.rejects(client.artifacts.restore(artifact.id, 1, edited.revision), /available/)
    const hiddenArchive = await client.artifacts.archive(artifact.id, true, edited.revision)
    assert.deepEqual(hiddenArchive.versions, [], 'Metadata mutation cannot accidentally return private raw versions')
  }
  const client = createFixtureClient(), initial = await client.load()
  const session = initial.sessions.find(item => item.id !== initial.companionSessionId && initial.conversations[item.id]?.messages.at(-1)?.role === 'assistant')
  const message = initial.conversations[session.id].messages.at(-1)
  const { artifactPreviewState } = load('src/lib/api/artifact-snapshot.ts')
  const annotated = structuredClone(initial)
  annotated.conversations[session.id].messages.at(-1).citations = [{ id: 'supplied', label: 'Supplied source', excerpt: 'Supplied excerpt' }]
  assert.deepEqual(artifactPreviewState(annotated, []).messages.find(item => item.sessionId === session.id && item.id === message.id).citations, annotated.conversations[session.id].messages.at(-1).citations, 'The canonical adapter forwards citation evidence to artifact source copies')
  const taskInput = { outcome: 'Review saved output', criteria: ['Owner checked it'], sessionId: session.id, agentId: session.agentId }
  let task = await client.tasks.create(taskInput)
  let artifact = await client.artifacts.createFromMessage({ sessionId: session.id, messageId: message.id, title: 'Reviewed response', taskId: task.id })
  assert.equal(artifact.taskAvailability, 'available')
  await client.updateConversation(session.id, { privacy: { memoryDisabled: true } })
  artifact = (await client.load()).artifacts[0]
  assert.equal(artifact.privateOrigin, true)
  assert.equal(artifact.privacy.memoryDisabled, true)
  assert.equal((await client.artifacts.export(artifact.id)).privateOrigin, true, 'Owner export retains explicit private origin metadata')
  await client.updateConversation(session.id, { privacy: { memoryDisabled: false, harnessDisabled: true } })
  assert.equal((await client.load()).artifacts[0].privateOrigin, true)
  await client.updateConversation(session.id, { incognito: false, archived: true })
  assert.equal((await client.load()).artifacts[0].availability, 'source-archived')
  assert.equal((await client.artifacts.export(artifact.id)).text, message.text, 'Archive preserves owner-readable output')
  await assert.rejects(client.artifacts.appendVersion(artifact.id, { content: { kind: 'markdown', text: 'No' } }, artifact.revision), /available/)
  await client.updateConversation(session.id, { archived: false })
  const other = await client.createConversation(session.agentId)
  task = await client.tasks.update(task.id, { ...taskInput, sessionId: other.id }, task.revision)
  assert.equal((await client.load()).artifacts[0].taskAvailability, 'origin-changed')
  await assert.rejects(client.artifacts.createFromMessage({ sessionId: session.id, messageId: message.id, title: 'Wrong task', taskId: task.id }), /must belong/)
  task = await client.tasks.update(task.id, taskInput, task.revision)
  task = await client.tasks.cancel(task.id, 'Review complete, no execution claimed.', task.revision)
  await client.tasks.archive(task.id, true, task.revision)
  assert.equal((await client.load()).artifacts[0].taskAvailability, 'archived')
  let authored = await client.artifacts.create({ title: 'Owner table', content: { kind: 'table', columns: ['Formula'], rows: [['=SUM(A1)']] } })
  assert.equal(authored.origin, 'owner-authored')
  const first = await client.artifacts.export(authored.id)
  assert.ok(first.text.includes("'=SUM"))
  authored = await client.artifacts.appendVersion(authored.id, { content: { kind: 'code', text: '<script>not executed</script>', language: 'html' } }, authored.revision)
  assert.equal((await client.artifacts.export(authored.id)).mime, 'text/plain;charset=utf-8')
  assert.ok((await client.artifacts.export(authored.id)).filename.endsWith('.html.txt'))
  await assert.rejects(client.artifacts.restore(authored.id, 1, authored.revision - 1), /changed/)
  authored = await client.artifacts.restore(authored.id, 1, authored.revision)
  assert.equal(authored.currentVersion, 3)
  assert.deepEqual(authored.versions[0].content, authored.versions[2].content)
  assert.equal((await client.load()).artifacts.find(item => item.id === authored.id).versions.length, 3)
  const beforeRead = await client.load()
  await client.artifacts.list()
  await client.artifacts.export(authored.id)
  const afterRead = await client.load()
  assert.deepEqual(afterRead.tasks, beforeRead.tasks)
  assert.deepEqual(afterRead.conversations, beforeRead.conversations)
  assert.deepEqual(afterRead.jobs, beforeRead.jobs)
  assert.deepEqual((await createFixtureClient().load()).artifacts, [])
  console.log('Artifact adapter safe snapshots, source redaction/deletion/edit, privacy/archive, task origin, version/export and no-execution checks passed.')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
