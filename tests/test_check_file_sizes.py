"""The file-size guard: its limit, its allowlist rules and its generated-file skip."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "check_file_sizes.py"
ALLOWLIST = "file-size-allowlist.txt"


def write_lines(root: Path, name: str, count: int, first_line: str = "x = 1") -> None:
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    body = [first_line] + ["x = 1"] * (count - 1)
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def make_repo(tmp_path: Path, allowlist: str = "") -> None:
    if allowlist:
        (tmp_path / ALLOWLIST).write_text(allowlist + "\n", encoding="utf-8")
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True, capture_output=True)
    subprocess.run(["git", "add", "-A"], cwd=tmp_path, check=True, capture_output=True)


def run_guard(tmp_path: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )


def test_at_the_limit_passes(tmp_path):
    write_lines(tmp_path, "big.py", 600)
    make_repo(tmp_path)
    result = run_guard(tmp_path)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "file sizes ok" in result.stdout


def test_one_line_over_the_limit_fails(tmp_path):
    write_lines(tmp_path, "big.py", 601)
    make_repo(tmp_path)
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert "big.py: 601 lines, limit 600. Split it by concern." in result.stdout


def test_allowlisted_file_may_sit_at_its_recorded_size(tmp_path):
    write_lines(tmp_path, "big.py", 700)
    make_repo(tmp_path, "big.py 700")
    result = run_guard(tmp_path)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "file sizes ok" in result.stdout


def test_allowlisted_file_growing_past_its_entry_fails(tmp_path):
    write_lines(tmp_path, "big.py", 701)
    make_repo(tmp_path, "big.py 700")
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert (
        "big.py: grew to 701 lines; it is allowlisted at 700 and may only shrink."
        in result.stdout
    )


def test_allowlisted_file_that_shrank_but_still_over_limit_asks_to_lower(tmp_path):
    write_lines(tmp_path, "big.py", 650)
    make_repo(tmp_path, "big.py 700")
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert (
        "big.py: shrank to 650 lines; lower its entry in file-size-allowlist.txt from 700."
        in result.stdout
    )


def test_allowlisted_file_back_under_the_limit_asks_to_delete_the_entry(tmp_path):
    write_lines(tmp_path, "big.py", 590)
    make_repo(tmp_path, "big.py 700")
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert (
        "big.py: now 590 lines, under the limit; delete its line from "
        "file-size-allowlist.txt." in result.stdout
    )


def test_allowlisted_file_no_longer_tracked_fails(tmp_path):
    make_repo(tmp_path, "gone.py 700")
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert (
        "gone.py: listed in file-size-allowlist.txt but no longer tracked; delete the line."
        in result.stdout
    )


def test_generated_dashboard_types_are_ignored_even_when_long(tmp_path):
    write_lines(
        tmp_path,
        "dashboard/src/lib/api/generated/api.d.ts",
        700,
        first_line="// Generated by scripts/api-types.mjs",
    )
    make_repo(tmp_path)
    result = run_guard(tmp_path)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "file sizes ok" in result.stdout


def test_a_file_in_the_generated_directory_without_the_generator_header_counts(tmp_path):
    write_lines(
        tmp_path,
        "dashboard/src/lib/api/generated/api.d.ts",
        700,
        first_line="// handwritten",
    )
    make_repo(tmp_path)
    result = run_guard(tmp_path)
    assert result.returncode == 1
    assert "700 lines, limit 600. Split it by concern." in result.stdout