"""Refusals of the file-size check (scripts/check_file_sizes.py) and the release bump
(scripts/release_bump.py). Git and the file system are a temporary folder; nothing is tagged or pushed."""

from __future__ import annotations

import pytest

from scripts import check_file_sizes, release_bump
from scripts.release_bump import BumpError

# ---- check_file_sizes -------------------------------------------------------------------------


@pytest.fixture
def sizes(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(check_file_sizes, "LIMIT", 3)
    tracked: list[str] = []
    monkeypatch.setattr(check_file_sizes, "tracked_sources", lambda: tracked)

    def add(name: str, lines: int) -> None:
        (tmp_path / name).write_text("x\n" * lines, encoding="utf-8")
        tracked.append(name)

    return add


def test_a_file_over_the_limit_fails(sizes, capsys):
    sizes("big.py", 5)
    assert check_file_sizes.main() == 1
    assert "big.py: 5 lines, limit 3" in capsys.readouterr().out


def test_small_files_pass(sizes, capsys):
    sizes("small.py", 2)
    assert check_file_sizes.main() == 0
    assert "file sizes ok" in capsys.readouterr().out


def test_allowlisted_file_may_not_grow(sizes, capsys, tmp_path):
    sizes("big.py", 6)
    (tmp_path / "file-size-allowlist.txt").write_text("big.py 5  # old\n\n", encoding="utf-8")
    assert check_file_sizes.main() == 1
    assert "grew to 6 lines" in capsys.readouterr().out


def test_allowlisted_file_back_under_the_limit_must_leave_the_list(sizes, capsys, tmp_path):
    sizes("big.py", 2)
    (tmp_path / "file-size-allowlist.txt").write_text("big.py 5\n", encoding="utf-8")
    assert check_file_sizes.main() == 1
    assert "delete its line" in capsys.readouterr().out


def test_allowlist_entry_for_an_untracked_file_fails(sizes, capsys, tmp_path):
    sizes("small.py", 1)
    (tmp_path / "file-size-allowlist.txt").write_text("gone.py 9\n", encoding="utf-8")
    assert check_file_sizes.main() == 1
    assert "gone.py: listed" in capsys.readouterr().out


def test_generated_declarations_are_recognised_by_their_first_line(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    folder = tmp_path / "dashboard/src/lib/api/generated"
    folder.mkdir(parents=True)
    (folder / "a.d.ts").write_text("// Generated by scripts/api-types.mjs\nx\n", encoding="utf-8")
    (folder / "b.d.ts").write_text("// hand written\n", encoding="utf-8")
    prefix = "dashboard/src/lib/api/generated/"
    assert check_file_sizes.generated(prefix + "a.d.ts")
    assert not check_file_sizes.generated(prefix + "b.d.ts")
    assert not check_file_sizes.generated(prefix + "missing.d.ts")
    assert not check_file_sizes.generated(prefix + "a.ts")
    assert not check_file_sizes.generated("other/a.d.ts")


# ---- release_bump -----------------------------------------------------------------------------

PINS = {f"{key}_VERSION": "1.2.3" for _, key in release_bump.MODULES}


def test_set_env_needs_exactly_one_line():
    assert release_bump.set_env("A=1\nB=2\n", "A", "9") == "A=9\nB=2\n"
    for text in ("B=2\n", "A=1\nA=2\n"):
        with pytest.raises(BumpError, match="exactly once"):
            release_bump.set_env(text, "A", "9")


def test_env_values_skips_comments_and_lines_without_equals():
    assert release_bump.env_values("# A=1\nB = 2\nnot a pair\n") == {"B": "2"}


def test_changelog_refuses_an_existing_version():
    text = "## Unreleased\n\n- x\n\n## 0.6.0\n\n- old\n"
    with pytest.raises(BumpError, match="already has a section"):
        release_bump.bump_changelog(text, "0.6.0", PINS)


@pytest.mark.parametrize("text", ["## 0.5.0\n- old\n", "## Unreleased\n\n\n## 0.5.0\n- old\n"])
def test_changelog_refuses_an_empty_unreleased_section(text):
    with pytest.raises(BumpError, match="nothing under"):
        release_bump.bump_changelog(text, "0.6.0", PINS)


def test_changelog_moves_entries_under_the_new_version_with_the_pins():
    text = "# Log\n\n## Unreleased\n\n- feature\n\n## 0.5.0\n\n- old\n"
    out = release_bump.bump_changelog(text, "0.6.0", PINS)
    assert "## Unreleased\n\n## 0.6.0\n\n- feature\n" in out
    assert "| Pi | v1.2.3 |" in out and out.endswith("## 0.5.0\n\n- old\n")


def test_run_reports_a_failing_command():
    with pytest.raises(BumpError, match="failed"):
        release_bump.run("python", "-c", "import sys; sys.exit(3)")


@pytest.mark.parametrize("version", ["1.2", "v1.2.3", "1.2.3.4", "", "a.b.c"])
def test_main_refuses_a_malformed_version(version, capsys):
    assert release_bump.main([version]) == 1
    assert "version must look like" in capsys.readouterr().err


def test_main_refuses_uncommitted_dashboard_changes(monkeypatch, capsys):
    monkeypatch.setattr(release_bump, "run", lambda *command: " M dashboard/x.ts")
    assert release_bump.main(["1.2.3"]) == 1
    assert "uncommitted changes" in capsys.readouterr().err


def test_main_refuses_a_short_pi_commit_before_writing(monkeypatch, tmp_path, capsys):
    (tmp_path / "scripts").mkdir()
    (tmp_path / "versions.env").write_text(
        "CONKER_VERSION=0.1.0\nCONKER_DASHBOARD_REVISION=abc\n", encoding="utf-8"
    )
    (tmp_path / "CHANGELOG.md").write_text("## Unreleased\n\n- x\n\n## 0.1.0\n", encoding="utf-8")
    monkeypatch.setattr(release_bump, "ROOT", tmp_path)
    monkeypatch.setattr(
        release_bump, "run", lambda *command: "" if command[1] == "status" else "a" * 40
    )
    monkeypatch.setattr(
        release_bump,
        "env_values",
        lambda text: PINS,
    )
    assert release_bump.main(["1.2.3", "--pi-sha", "abc123"]) == 1
    assert "40-character" in capsys.readouterr().err
    assert "CONKER_VERSION=0.1.0" in (tmp_path / "versions.env").read_text(encoding="utf-8")


def test_dry_run_writes_nothing(monkeypatch, tmp_path, capsys):
    env = "CONKER_VERSION=0.1.0\nCONKER_DASHBOARD_REVISION=abc\n" + "".join(
        f"{key}=1.2.3\n" for key in PINS
    )
    (tmp_path / "versions.env").write_text(env, encoding="utf-8")
    (tmp_path / "CHANGELOG.md").write_text("## Unreleased\n\n- x\n\n## 0.1.0\n", encoding="utf-8")
    monkeypatch.setattr(release_bump, "ROOT", tmp_path)
    monkeypatch.setattr(
        release_bump, "run", lambda *command: "" if command[1] == "status" else "a" * 40
    )
    assert release_bump.main(["1.2.3", "--dry-run"]) == 0
    assert "Would prepare 1.2.3" in capsys.readouterr().out
    assert (tmp_path / "versions.env").read_text(encoding="utf-8") == env
